/** 服务端/历史数据里的 emoji 图标 → SVG；认不出就原样返回。 */
export function iconFor(x) {
  if (!x) return '';
  const n = FROM_EMOJI[x] || FROM_EMOJI[x.replace(/️/g, '')];
  return n ? icon(n) : x;
}

/** 注入 sprite。启动时调一次。 */
export function mountIcons() {
  if (document.getElementById('c4-icons')) return;
  document.body.insertAdjacentHTML('afterbegin', SPRITE);
}
